addArchRGenome("hg38")

proj <- loadArchRProject(path = "/COMMA/results/scatac/ArchR/vascular_clustered", showLogo = FALSE)
proj <- addGeneScoreMatrix(input = proj, force = TRUE)
gene_matrix <- getMatrixFromProject(ArchRProj = proj, useMatrix = "GeneScoreMatrix")
counts <- t(assay(gene_matrix))
cell_metadata <- as.data.frame(colData(gene_matrix))
genes <- as.data.frame(rowData(gene_matrix))
gene_metadata <- data.frame(gene_name = as.character(genes$name), chr = as.character(genes$seqnames), start = as.numeric(genes$start), end = as.numeric(genes$end))
rownames(gene_metadata) <- make.unique(gene_metadata$gene_name)
colnames(counts) <- rownames(gene_metadata)
stopifnot(identical(rownames(counts), rownames(cell_metadata)))
umap <- as.data.frame(getEmbedding(proj, embedding = "UMAP"))
umap <- umap[rownames(cell_metadata), , drop = FALSE]
adata <- AnnData(X = counts, obs = cell_metadata, var = gene_metadata)
adata$obsm$X_umap <- umap
adata$write_h5ad("/COMMA/results/data_submission/raw/genescore_matrix.h5ad")